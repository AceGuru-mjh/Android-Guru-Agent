    /**
     * 码点显示宽度：0（零宽）/ 1（正常）/ 2（宽）。
     *
     * 判定顺序（与 Termux WcWidth 一致）：
     * 1. 控制字符（C0/C1）→ 0；
     * 2. 零宽表命中 → 0；
     * 3. 宽表命中 → 2；
     * 4. 其余 → 1。
     */
    fun widthOf(codePoint: Int): Int = when {
        codePoint in 0x00..0x1F || codePoint in 0x7F..0x9F -> 0
        codePoint == 0x200D -> 0                            // ZWJ 显式优先（图形簇连接）
        inRanges(ZERO_WIDTH, codePoint) -> 0
        inRanges(WIDE, codePoint) -> 2
        else -> 1
    }

    /** 是否零宽（Mn/Me/Cf —— 组合标记/格式字符；非控制字符）。 */
    fun isZeroWidth(codePoint: Int): Boolean =
        codePoint >= 0x300 && widthOf(codePoint) == 0

    /** 是否宽字符（CJK/全角/emoji）。 */
    fun isWide(codePoint: Int): Boolean = widthOf(codePoint) == 2

    /** 二分查找：有序区间表命中判定。 */
    private fun inRanges(ranges: Array<Pair<Int, Int>>, cp: Int): Boolean {
        var lo = 0
        var hi = ranges.size - 1
        while (lo <= hi) {
            val mid = (lo + hi) ushr 1
            val (start, end) = ranges[mid]
            when {
                cp < start -> hi = mid - 1
                cp > end -> lo = mid + 1
                else -> return true
            }
        }
        return false
    }
